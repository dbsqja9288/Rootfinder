/** 서비스가 나가는 순서. 성격이 비슷한 것끼리 붙지 않게 섞었다. */
const ORDER = ["조선", "촌수", "운세", "성씨"];

/**
 * 하루 96회 — 15분에 한 번.
 *
 * 서비스 네 개가 돌아가므로 서비스당 하루 24회.
 * 문구가 서비스마다 12개라 같은 글은 하루 두 번만 나간다.
 *
 * 스레드 API 한도는 24시간당 250개다. 96회는 그 38% 수준이라 여유가 있다.
 * 다만 깃허브 액션의 예약 실행은 정시를 몇 분씩 밀거나 건너뛰는 일이 잦아서,
 * 실제로는 하루 80~95회 사이가 된다. 그래도 목표에는 충분하다.
 */
export const SLOT_COUNT = 96;

/** 지금이 그날의 몇 번째 슬롯인지. 15분 단위로 0~95. */
function slotIndex() {
  const now = new Date();
  return (now.getUTCHours() * 4 + Math.floor(now.getUTCMinutes() / 15)) % SLOT_COUNT;
}

/** 오늘이 며칠째인지. 날마다 시작점을 밀어 같은 시간에 같은 글이 안 나오게 한다. */
function dayNumber() {
  return Math.floor(Date.now() / 86400000);
}

/**
 * 지금 올릴 글 하나를 고른다.
 *
 * 서비스: 슬롯 순서를 4로 나눈 나머지 → 하루 96회면 서비스당 정확히 24회.
 * 문구:   (날짜 + 그날 몇 번째 차례인지) → 12개를 두 바퀴 돌아 같은 글이 하루 두 번.
 */
export function pickPost() {
  const forcedService = process.env.SERVICE;
  const forcedPost = process.env.POST_ID;

  const i = slotIndex();
  const key = forcedService && SERVICES[forcedService] ? forcedService : ORDER[i % ORDER.length];
  const svc = SERVICES[key];

  const all = Object.keys(svc.posts);
  const allowed = ACTIVE[key]?.filter((id) => all.includes(id));
  const ids = allowed && allowed.length > 0 ? allowed : all;

  // 그날 이 서비스의 몇 번째 차례인지
  const nth = Math.floor(i / ORDER.length);
  const day = dayNumber();

  const id = forcedPost && svc.posts[forcedPost] ? forcedPost : ids[(day + nth) % ids.length];
  // 댓글 타래는 따로 돌린다. 같은 원글이 다시 나가도 이야기가 달라진다.
  const chain = svc.chains[(day + nth + 1) % svc.chains.length];

  return {
    service: key,
    label: svc.label,
    id,
    image: svc.image,
    // ★ 원글에는 링크를 넣지 않는다.
    //   본문에 링크가 박혀 있으면 광고로 읽히고, 스레드도 외부 링크가 붙은 글의
    //   노출을 덜 준다. 궁금증만 남기고 링크는 마지막 댓글에서 준다.
    //   해시태그는 원글에 둔다 — 토픽은 원글 기준으로 잡히기 때문이다.
    text: `${svc.posts[id]}

${svc.tag}`,
    /** 원글 아래에 순서대로 달 댓글 5개. 마지막에만 링크가 들어 있다. */
    replies: chain,
    // X는 타래를 쓰지 않아 링크를 본문에 붙인다 (지금은 꺼져 있음)
    textX: `${svc.posts[id]}

${SITE}${svc.path}`,
  };
}
