/** B 문구 고르기. A와 같은 방식으로 돌린다. */
function pickBText() {
  const forced = process.env.B_VERSION;
  if (forced && B_VERSIONS[forced]) return B_VERSIONS[forced];

  const names = Object.keys(B_VERSIONS);
  return B_VERSIONS[names[nth("B") % names.length]];
}

