/** 서비스가 나가는 순서. 성격이 비슷한 것끼리 붙지 않게 섞었다. */
const ORDER = ["조선", "촌수", "운세", "성씨"];

/**
 * 하루 24회, 매시 정각(UTC 0~23시 전부).
 * 한국시간으로도 24시간 전부라 따로 적을 것이 없다.
 *
 * 워크플로의 cron과 같아야 서비스 교대가 정확히 맞는다.
 */
export const SLOTS = Array.from({ length: 24 }, (_, i) => i);

function slotIndex() {
  const h = new Date().getUTCHours();
  return SLOTS.indexOf(h) >= 0 ? SLOTS.indexOf(h) : 0;
}

/** 오늘이 며칠째인지. 날마다 시작점을 밀어 같은 시간에 같은 글이 안 나오게 한다. */
function dayNumber() {
  return Math.floor(Date.now() / 86400000);
}

/**
 * 지금 올릴 글 하나를 고른다.
 *
 * 서비스: 슬롯 순서를 4로 나눈 나머지 → 하루 24회면 서비스당 정확히 6회.
 * 문구:   (날짜 + 그날 몇 번째 차례인지) → 하루 안에 같은 글이 두 번 안 나온다.
 */
export function pickPost() {
  const forcedService = process.env.SERVICE;
  const forcedPost = process.env.POST_ID;

  const i = slotIndex();
  const key = forcedService && SERVICES[forcedService] ? forcedService : ORDER[i % ORDER.length];
  const svc = SERVICES[key];

  const all = Object.keys(svc.posts);
  const allowed = ACTIVE[key]?.filter((id) => all.includes(id));
  const ids = allowed && allowed.length > 0 ? allowed : all;

  let id;
  if (forcedPost && svc.posts[forcedPost]) {
    id = forcedPost;
  } else {
    // 그날 이 서비스의 몇 번째 차례인지
    const nth = Math.floor(i / ORDER.length);
    id = ids[(dayNumber() + nth) % ids.length];
  }

  const url = `${SITE}${svc.path}`;

  return {
    service: key,
    label: svc.label,
    id,
    image: svc.image,
    text: `${svc.posts[id]}

${url}
${svc.tag}`,
    // X는 링크가 붙으면 요금이 올라가서 태그를 빼고 보낸다 (지금은 꺼져 있음)
    textX: `${svc.posts[id]}

${url}`,
  };
}
